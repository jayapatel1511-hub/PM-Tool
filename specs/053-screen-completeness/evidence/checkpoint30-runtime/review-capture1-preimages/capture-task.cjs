// Read-only actual-SPA review captures. Synthetic HTTP only; no business commands.
const assert = require('node:assert/strict')
const { join } = require('node:path')
const tests = join(process.cwd(), 'tests')
const { newMockPage } = require(join(tests, 'platform-fixtures.cjs'))
const f = require(join(tests, 'task-sections.fixture.cjs'))
const base = process.env.TUESDAY_UI_BASE_URL
assert.ok(base && ['127.0.0.1', 'localhost'].includes(new URL(base).hostname))
;(async () => {
  const ui = await newMockPage(base, { events: false }), { page } = ui, source = f.world()
  const errors = [], unexpected = [], commands = []
  source.flags.visual_system = true
  source.change({ rowVersion: 1, markedAt: f.stamp, note: 'Synthetic contribution: foundation checks complete', canMark: false, canWithdraw: true })
  const shell = new Set(['config', 'reference', 'workspaces', 'views', 'me/notifications/pulse', 'me/notifications/unread-count', 'events'])
  try {
    page.setDefaultTimeout(15000)
    page.on('pageerror', error => errors.push(error.message))
    await page.route('**/api/**', async route => {
      const request = route.request(), url = new URL(request.url()), name = url.pathname.replace('/api/v1/', '')
      const problem = (status, detail) => route.fulfill({ status, json: { status, detail } })
      if (request.method() === 'POST' && name === 'me/sign-in') return route.fallback()
      if (request.method() !== 'GET') { commands.push(request.method() + ' ' + name); return problem(405, 'Read-only capture') }
      if (name === 'me') return route.fulfill({ headers: { 'x-hub-build': 'mock-build-a' }, json: source.actor })
      if (name === 'projects') return route.fulfill({ json: source.projects })
      if (name === 'tasks') return route.fulfill({ json: source.tasks() })
      if (name === 'tasks/' + f.ids.task) return route.fulfill({ json: source.detail(f.ids.task) })
      if (name === 'projects/' + f.ids.project || name === 'projects/' + source.project.projectNumber) return route.fulfill({ json: source.project })
      if (name === 'projects/' + f.ids.project + '/tasks') return route.fulfill({ json: source.tasks() })
      if (name === 'projects/' + f.ids.project + '/deliverables' || name === 'projects/' + f.ids.project + '/milestones') return route.fulfill({ json: [] })
      if (name === 'tasks/' + f.ids.task + '/dependencies') return route.fulfill({ json: source.dependencies })
      if (name === 'items/Task/' + f.ids.task + '/comments') return route.fulfill({ json: source.comments })
      if (name === 'items/Task/' + f.ids.task + '/links') return route.fulfill({ json: source.links })
      if (name === 'tasks/' + f.ids.task + '/activity/actors') return route.fulfill({ json: f.actors })
      if (name === 'items/Task/' + f.ids.task + '/activity') return route.fulfill({ json: f.historyPage(url.searchParams) })
      if (shell.has(name)) return route.fallback()
      unexpected.push('GET ' + name); return problem(501, 'Unexpected capture GET')
    })
    const capture = name => page.screenshot({ path: join(process.env.TUESDAY_EVIDENCE_DIR, name + '.png') })
    const navigation = () => page.getByRole('navigation', { name: 'Task sections', exact: true })
    await page.setViewportSize({ width: 1440, height: 1100 })
    await page.goto(base + '/tasks/' + f.ids.task)
    await navigation().waitFor()
    await page.getByText('Synthetic contribution: foundation checks complete', { exact: true }).waitFor()
    await capture('05-task-sections-desktop')
    await page.locator('[data-task-contribution-user="' + f.ids.viewer + '"]').scrollIntoViewIfNeeded()
    await capture('06-contribution-desktop')
    await page.setViewportSize({ width: 375, height: 900 })
    await page.goto(base + '/tasks?projects=all&panel=Task:' + f.ids.task)
    await navigation().waitFor()
    await navigation().getByRole('button', { name: 'History', exact: true }).click()
    await page.getByRole('combobox', { name: 'History person', exact: true }).waitFor()
    await capture('05-task-history-phone')
    await navigation().getByRole('button', { name: 'Details', exact: true }).click()
    await page.locator('[data-task-contribution-user="' + f.ids.viewer + '"]').scrollIntoViewIfNeeded()
    await page.getByRole('button', { name: 'Withdraw my mark', exact: true }).waitFor()
    await capture('06-contribution-phone')
    assert.deepEqual(errors, []); assert.deepEqual(unexpected, []); assert.deepEqual(commands, [])
    console.log(JSON.stringify({ status: 'PASS_READONLY_VISUAL', profile: 'work_screens + visual_system; finite synthetic HTTP', businessWrites: commands.length, framingOnly: true }))
  } finally { await ui.browser.close() }
})().catch(error => { console.error(error); process.exitCode = 1 })
