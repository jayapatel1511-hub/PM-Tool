// Packet 052 S08: phone menu/search remain accessible only for the visual-system rollout.
const assert = require('node:assert/strict')
const { chromium } = require('playwright')
const { clientConfig } = require('./config.fixture.cjs')
const { meView, referenceData } = require('./me.fixture.cjs')
const { homeRead } = require('./workspace.fixture.cjs')

const searchResponse = {
  q: 'bridge', exact: null,
  counts: { projects: 1, tasks: 0, deliverables: 0, milestones: 0, decisions: 0, handoffs: 0, reviews: 0, changes: 0, submissions: 0, allocations: 0, 'design-basis': 0, constraints: 0, commitments: 0, planning: 0, comments: 0, people: 0 },
  groups: { projects: [{ id: '00000000-0000-0000-0000-000000000201', projectNumber: 'BRG-201', name: 'Bridge review', client: 'Synthetic client', pm: 'Drawer Tester', status: 'Active' }], tasks: [], deliverables: [], milestones: [], decisions: [], handoffs: [], reviews: [], changes: [], submissions: [], allocations: [], 'design-basis': [], constraints: [], commitments: [], planning: [], comments: [], people: [] },
}

const base = process.env.TUESDAY_UI_BASE_URL
assert.ok(base && ['localhost', '127.0.0.1'].includes(new URL(base).hostname), 'Set TUESDAY_UI_BASE_URL to the local preview')

;(async () => {
  const browser = await chromium.launch({ headless: true, ...(process.env.CHROME_EXECUTABLE_PATH ? { executablePath: process.env.CHROME_EXECUTABLE_PATH } : {}) })
  try {
    for (const visual of [true, false]) {
      const page = await browser.newPage({ viewport: { width: 375, height: 812 }, reducedMotion: 'reduce' })
      page.setDefaultTimeout(8000)
      page.setDefaultNavigationTimeout(10000)
      await page.addInitScript(() => { sessionStorage.setItem('hub.devUser', 'sam@hub.test'); sessionStorage.setItem('hub.signedIn', '1') })
      await page.route('**/api/**', async route => {
        const request = route.request(); const pathname = new URL(request.url()).pathname.replace('/api/v1/', '')
        if (pathname === 'config') return route.fulfill({ json: clientConfig() })
        if (pathname === 'me') return route.fulfill({ json: meView({ id: '00000000-0000-0000-0000-000000000002', displayName: 'Drawer Tester', email: 'drawer@hub.test', capabilities: { admin: true, staff: true, templates: true, workload: true }, flags: { visual_system: visual } }) })
        if (pathname === 'reference' || pathname === 'workspaces' || pathname === 'views') return route.fulfill({ json: pathname === 'reference' ? referenceData() : [] })
        if (pathname === 'admin/settings') return route.fulfill({ json: [] })
        if (pathname === 'home') return route.fulfill({ json: homeRead({ projectId: '00000000-0000-0000-0000-000000000201' }) })
        if (pathname === 'search') return route.fulfill({ json: searchResponse })
        if (pathname === 'me/notifications/pulse' || pathname === 'me/notifications/unread-count') return route.fulfill({ json: {} })
        return request.method() === 'GET' ? route.fulfill({ status: 200, json: {} }) : route.fulfill({ status: 204, body: '' })
      })
      await page.goto(`${base}/admin/settings`, { waitUntil: 'domcontentloaded' })
      await page.waitForFunction(expected => document.documentElement.getAttribute('data-visual') === (expected ? 'v2' : null), visual)
      const menu = page.getByRole('button', { name: 'Main navigation' })
      const bottom = page.locator('nav.fixed.bottom-0')
      await bottom.waitFor()
      assert.equal(await bottom.getByRole('link', { name: 'My Work' }).count(), 1)
      assert.equal(await bottom.getByRole('link', { name: 'Notifications' }).count(), 1)
      if (!visual) {
        assert.equal(await menu.count(), 0, 'legacy phone has no visual menu button')
        await page.close(); continue
      }
      assert.equal(await page.locator('.visual-topbar button[aria-label="Search"]').count(), 1, 'visual phone has a topbar search icon')
      await menu.click()
      const dialog = page.getByRole('dialog')
      await dialog.waitFor()
      assert.deepEqual(await dialog.locator('ul a[href]').evaluateAll(xs => xs.map(x => x.getAttribute('href'))), await page.locator('.visual-sidebar ul a[href]').evaluateAll(xs => xs.map(x => x.getAttribute('href'))), 'phone drawer has the exact permissioned desktop list')
      assert.ok(await dialog.getByRole('link', { name: 'Home' }).count() > 0)
      await page.keyboard.press('Escape')
      await dialog.waitFor({ state: 'hidden' })
      assert.equal(await page.locator('[role="dialog"]:visible').count(), 0)
      assert.equal(await page.evaluate(() => document.activeElement?.getAttribute('aria-label')), 'Main navigation')
      await menu.click()
      await dialog.waitFor()
      const firstLink = dialog.getByRole('link', { name: 'My Work', exact: true })
      const close = dialog.getByRole('button', { name: 'Close', exact: true })
      await firstLink.focus()
      await page.keyboard.press('Shift+Tab')
      assert.equal(await close.evaluate(el => document.activeElement === el), true, 'backward Tab wraps from the first link to Close')
      await page.keyboard.press('Tab')
      assert.equal(await firstLink.evaluate(el => document.activeElement === el), true, 'forward Tab wraps from Close to the first link')
      const stops = await dialog.getByRole('link').count() + await dialog.getByRole('button').count()
      for (let i = 0; i < stops; i++) {
        await page.keyboard.press('Tab')
        assert.ok(await page.evaluate(() => document.activeElement?.closest('[role="dialog"]')), `focus stays inside throughout a complete cycle: ${i}`)
      }
      assert.equal(await firstLink.evaluate(el => document.activeElement === el), true, 'one full keyboard cycle returns to the first link')
      await dialog.getByRole('link', { name: 'Admin', exact: true }).focus()
      await page.keyboard.press('Escape')
      await dialog.waitFor({ state: 'hidden' })
      await page.waitForFunction(() => document.activeElement?.getAttribute('aria-label') === 'Main navigation')
      assert.equal(await menu.evaluate(el => document.activeElement === el), true, 'one Escape from a focused drawer link closes the drawer and returns focus')
      await menu.click(); await dialog.waitFor()
      await page.locator('[data-slot="sheet-overlay"]').click({ position: { x: 370, y: 4 } })
      await dialog.waitFor({ state: 'hidden' })
      await page.waitForFunction(() => document.activeElement?.getAttribute('aria-label') === 'Main navigation')
      assert.equal(await menu.evaluate(el => document.activeElement === el), true, 'backdrop dismissal returns focus to the opener')
      await menu.click()
      await dialog.getByRole('link', { name: 'Home', exact: true }).click()
      await page.waitForURL(/\/home$/)
      await dialog.waitFor({ state: 'hidden' })
      await page.waitForFunction(() => document.activeElement?.getAttribute('aria-label') === 'Main navigation')
      assert.equal(await menu.evaluate(el => document.activeElement === el), true, 'route navigation closes the drawer and returns focus to its still-present opener')
      const topSearch = page.locator('.visual-topbar button[aria-label="Search"]')
      await topSearch.click()
      await page.getByRole('dialog').getByRole('combobox').waitFor()
      await page.keyboard.press('Escape')
      await dialog.waitFor({ state: 'hidden' })
      await page.waitForFunction(() => document.activeElement === document.querySelector('.visual-topbar button[aria-label="Search"]'))
      assert.equal(await topSearch.evaluate(el => document.activeElement === el), true, 'top Search dismissal returns to the top Search control')
      const bottomSearch = bottom.getByRole('button', { name: 'Search' })
      await bottomSearch.click()
      await page.getByRole('dialog').getByRole('combobox').waitFor()
      await page.keyboard.press('Escape')
      await dialog.waitFor({ state: 'hidden' })
      await page.waitForFunction(() => document.activeElement === document.querySelector('nav.fixed.bottom-0 button'))
      assert.equal(await bottomSearch.evaluate(el => document.activeElement === el), true, 'bottom Search dismissal returns to the bottom Search control')
      await menu.focus(); await page.keyboard.press('/')
      await dialog.getByRole('combobox').waitFor()
      assert.equal(await dialog.getByRole('combobox').evaluate(el => el === document.activeElement), true, 'phone shortcut opens and focuses the actual search sheet')
      await dialog.getByRole('combobox').fill('within'); await page.keyboard.press('/')
      assert.equal(await dialog.getByRole('combobox').inputValue(), 'within/', 'editing a search input keeps its literal slash')
      await page.keyboard.press('Escape'); await dialog.waitFor({ state: 'hidden' })
      await menu.click(); await dialog.getByRole('link', { name: 'My Work', exact: true }).focus(); await page.keyboard.press('/')
      assert.equal(await dialog.getByRole('heading', { name: 'Main navigation', exact: true }).count(), 1, 'global shortcut does not replace an active modal')
      assert.equal(await page.getByRole('dialog').count(), 1)
      await page.setViewportSize({ width: 375, height: 480 })
      const lastLink = dialog.getByRole('link', { name: 'Admin', exact: true })
      await lastLink.focus(); await lastLink.scrollIntoViewIfNeeded()
      assert.equal(await lastLink.evaluate(el => el.getBoundingClientRect().bottom <= innerHeight), true, 'foot destinations stay reachable in a short phone drawer')
      assert.equal(await dialog.getByRole('button', { name: 'Close', exact: true }).evaluate(el => el.getBoundingClientRect().bottom <= innerHeight), true)
      await page.keyboard.press('Escape'); await dialog.waitFor({ state: 'hidden' })
      await page.setViewportSize({ width: 375, height: 812 })
      await menu.click(); await dialog.waitFor()
      await page.setViewportSize({ width: 800, height: 812 })
      await dialog.waitFor({ state: 'hidden' })
      await page.setViewportSize({ width: 375, height: 812 }); await menu.waitFor()
      assert.equal(await page.getByRole('dialog').count(), 0, 'returning to phone does not resurrect the menu')
      await topSearch.click(); await dialog.getByRole('combobox').waitFor()
      await page.setViewportSize({ width: 1440, height: 900 }); await dialog.waitFor({ state: 'hidden' })
      const desktopSearch = page.locator('.visual-topbar input[role="combobox"]')
      await desktopSearch.waitFor(); await page.locator('main').focus(); await page.keyboard.press('/')
      assert.equal(await desktopSearch.evaluate(el => el === document.activeElement), true, 'closing a phone sheet preserves the separate desktop Search ref')
      await desktopSearch.fill('')
      await page.setViewportSize({ width: 375, height: 812 }); await menu.waitFor()
      assert.equal(await page.getByRole('dialog').count(), 0, 'returning to phone does not resurrect Search')
      await menu.click(); await dialog.waitFor(); await page.goBack(); await page.waitForURL(/\/admin\/settings$/)
      await dialog.waitFor({ state: 'hidden' })
      await page.goForward(); await page.waitForURL(/\/home$/)
      assert.equal(await page.getByRole('dialog').count(), 0, 'history navigation closes the shell drawer and keeps it closed on return')
      await topSearch.click(); await dialog.getByRole('combobox').waitFor(); await page.goBack(); await page.waitForURL(/\/admin\/settings$/)
      await dialog.waitFor({ state: 'hidden' })
      await page.goForward(); await page.waitForURL(/\/home$/)
      assert.equal(await page.getByRole('dialog').count(), 0, 'history navigation also closes the search sheet')
      await bottom.getByRole('button', { name: 'Search' }).click()
      const searchDialog = page.getByRole('dialog')
      await searchDialog.getByRole('heading', { name: 'Search', exact: true }).waitFor()
      const searchbox = searchDialog.getByRole('combobox')
      await searchbox.waitFor()
      await searchbox.fill('bridge')
      const result = searchDialog.getByRole('option', { name: /Bridge review/ })
      await result.waitFor()
      await result.click()
      await page.waitForFunction(() => !document.querySelector('[role="dialog"]'))
      assert.match(page.url(), /\/projects\/BRG-201$/)
      assert.equal(await page.evaluate(() => document.documentElement.scrollWidth), 375, 'visual phone has no horizontal overflow')
      await page.close()
    }
    console.log('PASS: phone drawer complete forward/backward focus cycle, Escape/backdrop/navigation return, both Search openers, bottom links and legacy parity.')
  } finally { await browser.close() }
})().catch(error => { console.error(error); process.exitCode = 1 })
